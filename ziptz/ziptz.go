// Package ziptz resolves US ZIP codes to IANA time zones from about 1.3 KB of
// tables.
//
//	name, err := ziptz.Zone("94110")            // "America/Los_Angeles"
//	loc, err := ziptz.Location("10001")
//	abb, err := ziptz.Abbrev("94110", when)     // "PST" in January, "PDT" in July
//	gen, err := ziptz.Generic("94110")          // "PT", whatever the date
//
// Give all five digits and the answer is exact. Three digits -- the prefix
// alone -- gets the majority zone for that prefix, which is right for 33,558 of
// the 33,791 ZIP codes and wrong for the 233 that sit on the losing side of a
// zone boundary their prefix has to round the wrong way.
//
// No dependency beyond the standard library, and no I/O of its own: both tables
// are string constants in this package, so a lookup is a binary search and a
// short scan. [Location] is the only function that touches the system's time
// zone database, through [time.LoadLocation].
//
// Data: US Census ZCTA Gazetteer centroids (a US Government work, public
// domain) resolved through timezone-boundary-builder (ODbL).
//
// The Python module next door answers identically, ZIP for ZIP; both tables are
// generated into the two implementations in one pass by tools/genzips.py, and
// must never be edited by hand.
package ziptz

//go:generate python3 tools/genzips.py

import (
	"fmt"
	"time"
)

// Version is the release this source belongs to; the Python module carries the
// same string.
const Version = "0.1.0"

// runs maps US ZIP prefixes to time zones, run-length encoded as fixed
// four-byte records "NNNc": the 3-digit prefix a run starts at, then a zone
