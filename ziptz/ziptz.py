"""US ZIP codes to IANA time zones, from about 1.3 KB of tables.

    >>> import ziptz
    >>> ziptz.zone("94110")
    'America/Los_Angeles'
    >>> ziptz.location("10001").key
    'America/New_York'
    >>> ziptz.abbrev("94110", datetime(2026, 7, 15, tzinfo=timezone.utc))
    'PDT'
    >>> ziptz.generic("94110")
    'PT'

Give all five digits and the answer is exact. Three digits -- the prefix alone
-- gets the majority zone for that prefix, which is right for 33,558 of the
33,791 ZIP codes and wrong for the 233 that sit on the losing side of a zone
boundary their prefix has to round the wrong way.

No dependency beyond the standard library, and no I/O of its own: both tables
are string constants in this module, and the first lookup unpacks them into
dicts, so the tables stay small on disk and answering is a hash. `location()`
is the only function that touches the system's time zone database, through
`zoneinfo`.

Data: US Census ZCTA Gazetteer centroids (a US Government work, public domain)
resolved through timezone-boundary-builder (ODbL).

The Go package next door answers identically, ZIP for ZIP; both tables are
generated into the two implementations in one pass by tools/genzips.py, and
must never be edited by hand.

Copyright (c) 2026 cho. MIT licensed; see LICENSE. The tables below contain
information from timezone-boundary-builder, made available under the ODbL, and
from OpenStreetMap, (c) OpenStreetMap contributors; see NOTICE. Dropping this
one file next to whatever imports it is a supported way to use it -- keep this
paragraph when you do, since it is then the only attribution travelling with
the tables.
"""

# Annotations as strings, which is what lets the signatures below be spelled
# the modern way -- `datetime | None` rather than Optional[datetime] -- on the
# 3.9 this library still supports, where that syntax would otherwise raise at
# import time. Nothing here reads its own annotations at runtime.
from __future__ import annotations

from datetime import datetime, timezone as _timezone
from zoneinfo import ZoneInfo

__all__ = [
    "ZipError",
    "zone",
    "location",
    "abbrev",
    "generic",
    "prefix_zone",
    "exact_zone",
]

__version__ = "0.1.0"


class ZipError(ValueError):
    """A ZIP code this table cannot resolve, with a reason fit to print."""


# US ZIP prefixes to time zones, run-length encoded as fixed four-byte records
# "NNNc": the 3-digit prefix a run starts at, then a zone letter from ZONES.
